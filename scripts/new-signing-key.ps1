<#
.SYNOPSIS
  Creates the ECDSA P-256 signing key pair used to sign MiniTools releases (run once).
.DESCRIPTION
  - Private key PEM  -> %USERPROFILE%\.minitools\signing-key.pem (never inside the repo).
  - Public key       -> printed, and written to Shared/MiniTools.Updater/PublicKey.cs when that folder exists.
  Refuses to overwrite an existing key unless -Force is given (overwriting makes every already
  shipped app reject your future updates, because it embeds the old public key).
.PARAMETER KeyPath
  Where to store the private key (default: $env:MINITOOLS_SIGNING_KEY or %USERPROFILE%\.minitools\signing-key.pem).
#>
[CmdletBinding()]
param(
    [string]$KeyPath,
    [switch]$Force
)
$ErrorActionPreference = 'Stop'

$workRoot = Split-Path -Parent $PSScriptRoot
if (-not $KeyPath) {
    if ($env:MINITOOLS_SIGNING_KEY) { $KeyPath = $env:MINITOOLS_SIGNING_KEY }
    else { $KeyPath = Join-Path $env:USERPROFILE '.minitools\signing-key.pem' }
}
$KeyPath = [System.IO.Path]::GetFullPath($KeyPath)

if ((Test-Path $KeyPath) -and -not $Force) {
    Write-Warning "A signing key already exists: $KeyPath"
    Write-Warning "Not overwriting. Use -Force only if you really want to replace it (apps shipped with the old public key will reject new updates)."
    exit 1
}

$toolProj = Join-Path $workRoot 'scripts\tools\ManifestTool\ManifestTool.csproj'
dotnet build $toolProj -c Release --nologo -v q | Out-Null
if ($LASTEXITCODE -ne 0) { throw 'Building ManifestTool failed.' }
$toolDll = Join-Path $workRoot 'scripts\tools\ManifestTool\bin\Release\net10.0\ManifestTool.dll'

$keyArgs = @('keygen', '--out', $KeyPath)
if ($Force) { $keyArgs += '--force' }
$pub = (& dotnet $toolDll @keyArgs) -join "`n"
if ($LASTEXITCODE -ne 0) { throw 'Key generation failed.' }
$pub = $pub.Trim()

Write-Host ''
Write-Host "Private key saved to: $KeyPath" -ForegroundColor Green
Write-Host 'KEEP IT SECRET and BACK IT UP (password manager / offline). Never commit it. If it is lost, shipped apps can no longer be updated.' -ForegroundColor Yellow
Write-Host ''
Write-Host 'Public key:'
Write-Host $pub

$updaterDir = Join-Path $workRoot 'Shared\MiniTools.Updater'
if (Test-Path $updaterDir) {
    $cs = @"
namespace MiniTools.Updater;

/// <summary>Public key used to verify release signatures. Generated by scripts/new-signing-key.ps1. Safe to commit.</summary>
public static class PublicKey
{
    public const string Pem = """
$pub
""";
}
"@
    $target = Join-Path $updaterDir 'PublicKey.cs'
    [System.IO.File]::WriteAllText($target, $cs + "`n", (New-Object System.Text.UTF8Encoding($false)))
    Write-Host ''
    Write-Host "Wrote $target" -ForegroundColor Green
} else {
    Write-Host ''
    Write-Host 'Shared/MiniTools.Updater does not exist yet: PublicKey.cs was NOT written. Copy the public key above into it later.' -ForegroundColor Yellow
}

$oneLine = ($pub -replace "`r", '') -replace "`n", '\n'
Write-Host ''
Write-Host 'Server config: add this line to MiniToolsHub/deploy/.env (single line, literal \n):'
Write-Host "Hub__PublicKeyPem=$oneLine"
